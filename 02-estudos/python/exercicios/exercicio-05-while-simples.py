# Exercício

# Crie um programa que:

# Crie uma variável chamada contador iniciando em 1.
# Utilize um while para repetir enquanto o contador for menor ou igual a 10.
# Mostre o valor do contador na tela.
# Após mostrar o número, aumente o contador em 1.
# Quando o contador ultrapassar 10, o programa deve terminar.

# Resposta

contador = 1
while contador <= 10:
    print(contador)
    contador += 1